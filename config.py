# ==========================================
# ГЛОБАЛЬНЫЕ НАСТРОЙКИ (GLOBAL CONFIGURATION)
# Изменяйте эти параметры для настройки шестеренок
# ==========================================

# Основные параметры
DIAMETER = 100.0             # Желаемый ВНЕШНИЙ диаметр сферы (в мм)
TEETH = 32                  # Количество зубьев

# Тонкие настройки профиля зуба
PRESSURE_ANGLE_DEG = 20.0   # Угол зацепления в градусах (стандарт 20)
BACKLASH = 0.0              # Зазор (backlash) для свободного вращения, если нужно
ADDENDUM_COEF = 1.0         # Коэффициент высоты головки зуба (стандарт 1.0)
DEDENDUM_COEF = 1.2         # Коэффициент высоты ножки зуба (стандарт 1.2)
INVERT_PROFILE = True      # Если True, профиль поворачивается на половину шага (зубья становятся впадинами)

# Настройки для Monopole Gear
MONOPOLE_TEETH = 16         # Количество зубьев Monopole (определяет передаточное число, например 32:16 = 2:1)
MONOPOLE_BORE_DIAMETER = 16.0 # Диаметр сквозного отверстия в monopole gear (в мм)

# Имена файлов для экспорта
OUTPUT_SPHERE_STL = "spherical_gear.stl"
OUTPUT_MONOPOLE_STL = "monopole_gear.stl"
OUTPUT_PIN_STL = "hex_pin.stl"

# ==========================================
# 2. АВТОМАТИЧЕСКИЙ РАСЧЕТ ШТИФТОВ (PINS)
# ==========================================
import math

# Вычисляем параметры шестерни
calc_module = DIAMETER / (TEETH + 2 * ADDENDUM_COEF)
R_pitch = TEETH * calc_module / 2
R_root = R_pitch - DEDENDUM_COEF * calc_module

# Выбираем, в какую "долину" (между зубьями) от центра поставить штифты.
# 1 - самая близкая к центру
# 2 или 3 - шире, захватывает больше площади (около 50% сферы)
PIN_VALLEY_INDEX = 2

# Угол долины
pitch_angle = 360.0 / TEETH
if INVERT_PROFILE:
    # Если профиль инвертирован, 0 градусов - это долина
    valley_angle = PIN_VALLEY_INDEX * pitch_angle
else:
    # Иначе долина смещена на полшага
    valley_angle = (PIN_VALLEY_INDEX - 0.5) * pitch_angle

# Точное смещение для попадания ровно в перекрестие долин
PIN_OFFSET = R_root * math.sin(math.radians(valley_angle))

# ==========================================
# 2. НАСТРОЙКИ СБОРКИ И КРЕПЛЕНИЙ (ASSEMBLY OPTIONS)
# ==========================================

# Включатели/выключатели функций (можно легко отключить то, что не нужно)
ENABLE_PINS = True                # Вырезать ли шестигранные отверстия в сфере для соединения штифтами?
ENABLE_SCREWS = True              # Делать ли сквозные отверстия под стяжные винты в самой сфере?
ENABLE_THREADED_INSERTS = True    # Делать ли углубления под латунные вставки внутри штифтов (hex_pin)?

# Автоматические размеры штифтов (масштабируются под размер сферы)
PIN_DIAMETER = calc_module * 5.0           # Диаметр масштабируется от размера зуба
PIN_LENGTH = DIAMETER * 0.3                # Длина штифта (всегда 30% от диаметра сферы)
PIN_TOLERANCE = 0.20                       # Зазор 0.2 мм для FDM печати
PIN_HOLE_DEPTH = (PIN_LENGTH / 2.0) + 1.0  # Запас глубины 1 мм в каждой половинке сферы

# Настройки для резьбовых вставок (Heat-set inserts)
INSERT_HOLE_DIAMETER = 4.0                 # Под М3 вставку (4.5мм OD)
INSERT_HOLE_DEPTH = 8.0                    # Запас по глубине (8мм для вставки 5мм)

# Настройки для крепежных винтов сквозь сферу (если ENABLE_SCREWS = True)
SCREW_CLEARANCE_HOLE = 3.4                 # Отверстие для ножки винта М3
SCREW_HEAD_DIAMETER = 6.5                  # Углубление под шляпку винта М3 (DIN 912)
SCREW_CLAMP_THICKNESS = 10.0               # Толщина пластика зажима (постоянная, так как винты стандартные)
